param([switch]$Required)
. "$PSScriptRoot/common.ps1"
# Verified official stable PortableApps.com Installer 3.9.22, 2026-10-12.
$version='3.9.22'
$expected='689456f1fb1320c45e82a077afe6b87fb388fd3f75c41d9ee9ce8d45f3966b67'
$filename="PortableApps.comInstaller_$version.paf.exe"
$uri="https://downloads.sourceforge.net/project/portableapps/PortableApps.com%20Installer/$filename"
$toolArchive=Join-Path (Resolve-Path work) $filename
$extract=Join-Path (Resolve-Path work) 'official-installer-tool'
New-Item -ItemType Directory -Force $extract|Out-Null
try {
 & curl.exe --fail --location --retry 3 --retry-delay 4 --connect-timeout 25 --max-time 360 --output $toolArchive $uri
 if($LASTEXITCODE -ne 0){throw 'Official tool download failed'}
 Require ((Get-Item $toolArchive).Length -gt 1000000) 'Official tool download unexpectedly small'
 Require ((Get-FileHash $toolArchive -Algorithm SHA256).Hash.ToLowerInvariant() -eq $expected) 'Official installer SHA256 mismatch'
 Assert-PE $toolArchive
 $seven=SevenZip
 & $seven x '-y' "-o$extract" $toolArchive|Out-Host
 if($LASTEXITCODE -ne 0){throw 'Could not headlessly extract official PortableApps tool'}
 $tools=@(Get-ChildItem $extract -Recurse -File -Filter 'PortableApps.comInstaller.exe')
 Require ($tools.Count -eq 1) "Expected exactly one real PortableApps.comInstaller.exe, got $($tools.Count)"
 Assert-PE $tools[0].FullName
 $up=Get-Content work/upstream.json -Raw|ConvertFrom-Json
 $stage=Join-Path (Resolve-Path .) 'work/BravePortable'
 $start=Get-Date
 $psi=New-Object Diagnostics.ProcessStartInfo
 $psi.FileName=$tools[0].FullName
 $psi.Arguments='"'+$stage+'"'
 $psi.WorkingDirectory=(Resolve-Path work).Path
 $psi.UseShellExecute=$false;$psi.CreateNoWindow=$true
 $psi.RedirectStandardOutput=$false;$psi.RedirectStandardError=$false
 $p=[Diagnostics.Process]::Start($psi)
 try {if(-not $p.WaitForExit(240000)){try{$p.Kill($true)}catch{};throw 'Official PAF compiler timed out after 240 seconds (likely interactive wizard or blocking condition)'}
  Set-Content work/paf-compiler.log -Value "Official tool version $version; exit code $($p.ExitCode). Console output is in the GitHub Actions step log." -Encoding utf8
  Write-Host "Official tool return code: $($p.ExitCode)"
  Require ($p.ExitCode -eq 0) "Official PAF compiler exited with nonzero status: $($p.ExitCode)"
 }finally{$p.Dispose()}
 $pafs=@(Get-ChildItem work,dist -Recurse -File -Filter '*.paf.exe' |Where-Object {$_.FullName -ne $toolArchive -and $_.LastWriteTime -ge $start.AddSeconds(-5) -and $_.Name -match '(?i)^BravePortable.*\.paf\.exe$'})
 Require ($pafs.Count -eq 1) "Official compiler did not generate exactly one matching BravePortable .paf.exe ($($pafs.Count) found); inspect work/paf-compiler.log"
 $dest=Join-Path (Resolve-Path dist) "BravePortable_$($up.Version)_brave-r3_Win64.paf.exe"
 Move-Item -LiteralPath $pafs[0].FullName -Destination $dest -Force
 Assert-PE $dest
 Invoke-ArchiveTest $dest
 "{0}  {1}" -f (Get-FileHash $dest -Algorithm SHA256).Hash.ToLowerInvariant(),(Split-Path $dest -Leaf)|Set-Content "$dest.sha256" -Encoding ascii
 Write-Host "Official PortableApps.com Installer PAF generated by ${version}: $dest"
} catch {
 Write-Warning "Official PAF attempt failed: $_"
 Get-ChildItem dist -Filter '*.paf.exe' -File -ErrorAction SilentlyContinue | Remove-Item -Force
 if($Required){throw}
 # Never fabricate an installer, and leave the independently validated ZIP intact.
}
